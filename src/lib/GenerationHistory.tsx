import React, { useState, useEffect } from 'react';
import { 
  History, 
  Search, 
  Calendar, 
  Download, 
  ExternalLink, 
  Loader2,
  Sparkles,
  CheckCircle2,
  XCircle,
  Clock,
  ArrowRight
} from 'lucide-react';
import { motion } from 'framer-motion';
import { useAuth } from './AuthProvider';
import { db } from './firebase';
import { collection, query, where, getDocs, orderBy, limit } from 'firebase/firestore';

export function GenerationHistory() {
  const { user } = useAuth();
  const [generations, setGenerations] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (user) {
      fetchGenerations();
    }
  }, [user]);

  const fetchGenerations = async () => {
    if (!user) return;
    setLoading(true);
    try {
      const q = query(
        collection(db, 'generations'),
        where('userId', '==', user.uid),
        orderBy('createdAt', 'desc'),
        limit(50)
      );
      const querySnapshot = await getDocs(q);
      setGenerations(querySnapshot.docs.map(doc => ({ id: doc.id, ...doc.data() })));
    } catch (error) {
      console.error("Error fetching generations:", error);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="max-w-7xl mx-auto p-8 space-y-10">
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-6">
        <div>
          <h1 className="text-3xl font-bold text-white mb-2 flex items-center gap-3">
            <History className="w-8 h-8 text-indigo-500" />
            Generation History
          </h1>
          <p className="text-zinc-500">Track every creative spark generated by PULSE AI.</p>
        </div>
        <div className="flex items-center gap-3">
          <button className="p-3 bg-zinc-900 border border-zinc-800 rounded-2xl text-zinc-400 hover:text-white transition-all">
            <Calendar className="w-5 h-5" />
          </button>
          <button className="p-3 bg-zinc-900 border border-zinc-800 rounded-2xl text-zinc-400 hover:text-white transition-all">
            <Search className="w-5 h-5" />
          </button>
        </div>
      </div>

      {loading ? (
        <div className="flex flex-col items-center justify-center py-20 gap-4">
          <Loader2 className="w-12 h-12 animate-spin text-indigo-500" />
          <p className="text-zinc-500 font-medium">Retrieving history...</p>
        </div>
      ) : generations.length > 0 ? (
        <div className="space-y-4">
          {generations.map((gen, i) => (
            <motion.div
              key={gen.id}
              initial={{ opacity: 0, x: -20 }}
              animate={{ opacity: 1, x: 0 }}
              transition={{ delay: i * 0.05 }}
              className="bg-zinc-900 border border-zinc-800 rounded-2xl p-6 flex flex-col md:flex-row md:items-center gap-6 hover:border-zinc-700 transition-all"
            >
              <div className={`w-12 h-12 rounded-xl flex items-center justify-center shrink-0 ${
                gen.status === 'completed' ? 'bg-emerald-500/10 text-emerald-500' : 
                gen.status === 'failed' ? 'bg-red-500/10 text-red-500' : 'bg-indigo-500/10 text-indigo-500'
              }`}>
                {gen.status === 'completed' ? <CheckCircle2 className="w-6 h-6" /> : 
                 gen.status === 'failed' ? <XCircle className="w-6 h-6" /> : <Sparkles className="w-6 h-6 animate-pulse" />}
              </div>

              <div className="flex-1 min-w-0 space-y-1">
                <div className="flex items-center gap-2">
                  <h3 className="text-white font-bold uppercase tracking-widest text-xs">{gen.type}</h3>
                  <span className="text-zinc-700">·</span>
                  <p className="text-xs text-zinc-500 flex items-center gap-1">
                    <Clock className="w-3 h-3" />
                    {gen.createdAt?.toDate().toLocaleString()}
                  </p>
                </div>
                <p className="text-zinc-400 text-sm truncate">{gen.prompt || gen.title || 'No prompt info'}</p>
              </div>

              <div className="flex items-center gap-4">
                <div className="text-right hidden md:block">
                  <p className="text-white font-bold text-sm">{gen.cost || 0} Credits</p>
                  <p className="text-[10px] font-black text-zinc-600 uppercase tracking-tighter">Transaction: {gen.status}</p>
                </div>
                <div className="h-8 w-px bg-zinc-800 hidden md:block" />
                <div className="flex items-center gap-2">
                  {gen.resultUrl && (
                    <a 
                      href={gen.resultUrl} 
                      target="_blank" 
                      rel="noreferrer"
                      className="p-3 rounded-xl bg-zinc-800 text-zinc-400 hover:text-white transition-all"
                    >
                      <Download className="w-5 h-5" />
                    </a>
                  )}
                  <button className="p-3 rounded-xl bg-indigo-600 text-white hover:bg-indigo-500 transition-all group">
                    <ArrowRight className="w-5 h-5 group-hover:translate-x-1 transition-transform" />
                  </button>
                </div>
              </div>
            </motion.div>
          ))}
        </div>
      ) : (
        <div className="flex flex-col items-center justify-center py-20 text-center space-y-4">
          <div className="w-20 h-20 rounded-full bg-zinc-900 border border-zinc-800 flex items-center justify-center">
            <History className="w-10 h-10 text-zinc-800" />
          </div>
          <div className="max-w-xs">
            <h3 className="text-white font-bold mb-1">History is Clean</h3>
            <p className="text-sm text-zinc-500">Your AI-powered production journey starts here. Generations will appear as you create.</p>
          </div>
        </div>
      )}
    </div>
  );
}
